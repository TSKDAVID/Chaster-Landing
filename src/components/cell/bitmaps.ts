/** Compose a string into one bitmap with a 2-column gap between glyphs. Unknown characters become a gap. */
export function composeText(text: string): string[] {
  const glyphs = [...text].map((ch) => NUMERALS[ch] ?? ["..", "..", "..", "..", "..", "..", ".."]);
  const rows: string[] = Array.from({ length: 7 }, () => "");
  glyphs.forEach((g, gi) => {
    for (let r = 0; r < 7; r++) rows[r] += (gi > 0 ? ".." : "") + g[r];
  });
  return rows;
}
